/**
 * Built-in node kinds with no Dagster translation: the engine declares them
 * NOT-SUPPORTED so the translator fails loudly instead of silently dropping them
 * (SAA-193 §7.3). `while`/`until` are sensor/extension-point-only in Dagster;
 * `humanApproval` and `break` have no OSS equivalent.
 */
export const DAGSTER_UNSUPPORTED_KINDS = new Set<string>([
  "core.flow.break",
  "core.flow.humanApproval",
  "core.loop.while",
  "core.loop.until",
]);

