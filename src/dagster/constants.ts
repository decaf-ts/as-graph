/**
 * @module as-graph/dagster/constants
 * @summary Constants for the Dagster graph execution backend (SAA-195).
 * @description Pinned Dagster engine version/source, generated-module constants,
 * the Python import allowlist (SAA-193 C9), and the machine-readable error codes
 * the translator, event bridge, and backend raise. Dagster is a Python orchestration
 * engine with no official JavaScript runtime, so this wrapper is a pure translation
 * + host-injected client port; the pin records which engine contract the generated
 * artifacts target.
 */

/**
 * Backend flavour under which {@link DagsterGraphExecutionBackend} registers itself
 * in the {@link GraphExecutionBackendRegistry}.
 */
export const DAGSTER_BACKEND_FLAVOUR = "dagster";

/**
 * Pinned Dagster engine version. Verified as the latest release on PyPI
 * (`https://pypi.org/pypi/dagster/json`) at implementation time and recorded in
 * every generated artifact header so a translation is always traceable to the engine
 * contract it targets.
 */
export const DAGSTER_PINNED_VERSION = "1.13.25";

/**
 * Provenance of the {@link DAGSTER_PINNED_VERSION} pin (the PyPI JSON metadata
 * endpoint the version was read from).
 */
export const DAGSTER_PINNED_SOURCE = "https://pypi.org/pypi/dagster/json";

/**
 * PyPI distribution name of the pinned engine.
 */
export const DAGSTER_PINNED_DISTRIBUTION = "dagster";

/**
 * Name of the host-provided Dagster resource generated ops delegate execution to.
 * The resource is responsible for invoking the as-graph node executor for a kind; the
 * translator never inlines node behaviour or user data into generated op bodies.
 */
export const DAGSTER_RESOURCE_NAME = "as_graph";

/**
 * Run-tag namespace for all tracing data the wrapper attaches to a Dagster run
 * (SAA-193 C8). Free-form document strings never enter generated Python; they
 * travel as run tags under this namespace only.
 */
export const DAGSTER_TAG_NAMESPACE = "as-graph/";

/**
 * Maximum length of a generated Python identifier. Mirrors the conservative
 * identifier length most Python toolchains accept without truncation warnings.
 */
export const DAGSTER_IDENTIFIER_MAX_LENGTH = 63;

/**
 * The only Python module the generated artifact is allowed to import (SAA-193 C9).
 * Generated code references `dagster.*` exclusively, so the import set is always
 * exactly this single pinned, allowlisted module.
 */
export const DAGSTER_IMPORT_ALLOWLIST = ["dagster"] as const;

/**
 * The exact module header emitted at the top of every generated artifact.
 */
export const DAGSTER_GENERATED_HEADER =
  "# Generated by @decaf-ts/as-graph ./dagster. DO NOT EDIT.";

/**
 * Machine-readable error codes raised by the Dagster wrapper.
 */
export const DAGSTER_ERROR = {
  /** A workflow carries a code-mode surface and cannot be translated (SAA-193 C2). */
  CODE_MODE_UNSUPPORTED: "GRAPH_DAGSTER_CODE_MODE_UNSUPPORTED",
  /** A node kind has no Dagster translation and no host extension point (SAA-193 §7.3). */
  UNSUPPORTED_KIND: "GRAPH_DAGSTER_UNSUPPORTED_KIND",
  /** A condition path failed the validated grammar (SAA-193 C7). */
  PATH_REJECTED: "GRAPH_DAGSTER_PATH_REJECTED",
  /** A value embedded in the generated artifact is not JSON-safe (SAA-193 C10). */
  TRANSLATION_JSON_UNSAFE: "GRAPH_DAGSTER_TRANSLATION_JSON_UNSAFE",
  /** Generated code attempted to import a module outside the allowlist (SAA-193 C9). */
  IMPORT_NOT_ALLOWED: "GRAPH_DAGSTER_IMPORT_NOT_ALLOWED",
  /** A backend operation was requested without a wired Dagster client port. */
  CLIENT_NOT_CONFIGURED: "GRAPH_DAGSTER_CLIENT_NOT_CONFIGURED",
  /** Workflow listing/lookup was requested but the client port does not expose it. */
  WORKFLOWS_NOT_SUPPORTED: "GRAPH_DAGSTER_WORKFLOWS_NOT_SUPPORTED",
  /** A Dagster event type has no engine-agnostic mapping (SAA-193 §7.3). */
  EVENT_UNSUPPORTED: "GRAPH_DAGSTER_EVENT_UNSUPPORTED",
  /** The client failed to launch or terminate the run. */
  RUN_FAILED: "GRAPH_DAGSTER_RUN_FAILED",
} as const;

