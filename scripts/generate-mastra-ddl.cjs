#!/usr/bin/env node
/* global require, process, __dirname */
/* eslint-disable @typescript-eslint/no-require-imports -- plain Node script */
/**
 * Generates the Mastra storage bootstrap DDL (schema `mastra`) from the
 * installed `@mastra/pg` (`exportSchemas`), so it always matches the Mastra
 * version as-graph runs with.
 *
 * Usage: node scripts/generate-mastra-ddl.cjs [output.sql] [schema]
 *   (`npm run ddl:mastra`; output defaults to
 *   `docker/sql/0002_mastra_storage_schema.sql`)
 *
 * Regenerate after updating `@mastra/pg`/`@mastra/core`.
 */
const { writeFileSync } = require("node:fs");
const { join } = require("node:path");
const { exportSchemas } = require("@mastra/pg");

const [
  output = join(__dirname, "..", "docker", "sql", "0002_mastra_storage_schema.sql"),
  schema = "mastra",
] = process.argv.slice(2);

const ddl = exportSchemas(schema);
const body = ddl.slice(ddl.indexOf("CREATE SCHEMA IF NOT EXISTS"));
const tables = [
  ...new Set(
    [...body.matchAll(/CREATE TABLE IF NOT EXISTS "[^"]+"\."([^"]+)"/g)].map((m) => m[1])
  ),
];
const pg = require("@mastra/pg/package.json").version;
const core = require("@mastra/core/package.json").version;

const header = [
  "-- 0002_mastra_storage_schema.sql",
  `-- Bootstrap DDL for ALL Mastra storage domains in schema \`${schema}\`.`,
  "--",
  `-- GENERATED by \`as-graph/scripts/generate-mastra-ddl.cjs\` (\`npm run ddl:mastra\`)`,
  `-- from \`exportSchemas("${schema}")\` of @mastra/pg ${pg} (@mastra/core ${core}) —`,
  "-- do not edit by hand; regenerate after a Mastra update.",
  `-- ${tables.length} tables. Observability VNext event-sourced tables`,
  "-- (`mastra_span_events`, ...) belong to `PostgresStoreVNext` on schema",
  "-- `mastra_obs` — not part of this file.",
  "--",
  "-- Shipped with @decaf-ts/as-graph (`docker/sql/`): applied by its own",
  "-- integration setup and by deployments' bootstrap migration. Idempotent",
  "-- (IF NOT EXISTS).",
  "",
  "",
].join("\n");

writeFileSync(output, header + body);
console.log(`wrote ${output} (@mastra/pg ${pg}, ${tables.length} tables)`);
