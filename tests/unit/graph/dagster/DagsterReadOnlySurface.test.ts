/**
 * @module as-graph/tests/unit/graph/dagster/DagsterReadOnlySurface.test
 * @summary Grep-style read-only enforcement test for the Dagster driver surface.
 * @description Proves the owner mandate against the actual runtime exported
 * surface of `src/dagster` (the module object, not a source-text grep): no
 * Python source is emitted or embedded anywhere, the removed authoring exports no
 * longer exist, and every authoring capability row is `not_supported`.
 */
import * as dagster from "../../../../src/dagster";
import { DAGSTER_CAPABILITY_TABLE } from "../../../../src/dagster/capabilities";
import { DAGSTER_ERROR } from "../../../../src/dagster/constants";

/** Patterns that only ever appear in generated/embedded Python source. */
const PYTHON_SOURCE_PATTERNS: RegExp[] = [
  /@dagster\./,
  /\bimport\s+dagster\b/,
  /\bdef\s+[A-Za-z_]\w*\s*\(/,
  /dagster\.(Out|In|DynamicOut|DynamicOutput|ScheduleDefinition|sensor|job|graph)\s*\(/,
  /config_schema\s*=/,
  /\bexecute_node\s*\(/,
  /\bpoll_trigger\s*\(/,
  /_route\s*\(/,
  /_iter\s*\(/,
  /Generated by @decaf-ts\/as-graph/,
];

/** Recursively collects every string reachable from a value. */
function collectStrings(value: unknown, seen: Set<object>, out: string[]): void {
  if (value === null || value === undefined) return;
  if (typeof value === "string") {
    out.push(value);
    return;
  }
  if (typeof value === "function") {
    // The exported function/class source is part of the runtime surface.
    out.push(Function.prototype.toString.call(value));
    return;
  }
  if (typeof value !== "object") return;
  if (seen.has(value as object)) return;
  seen.add(value as object);
  if (Array.isArray(value)) {
    for (const entry of value) collectStrings(entry, seen, out);
    return;
  }
  if (value instanceof Set) {
    for (const entry of value) collectStrings(entry, seen, out);
    return;
  }
  if (value instanceof Map) {
    for (const [key, entry] of value) {
      collectStrings(key, seen, out);
      collectStrings(entry, seen, out);
    }
    return;
  }
  for (const entry of Object.values(value)) {
    collectStrings(entry, seen, out);
  }
}

describe("Dagster read-only surface", () => {
  it("emits or embeds no Python source anywhere on the exported surface", () => {
    const strings: string[] = [];
    collectStrings(dagster, new Set(), strings);
    const haystack = strings.join("\n");

    for (const pattern of PYTHON_SOURCE_PATTERNS) {
      expect(haystack).not.toMatch(pattern);
    }
  });

  it("no longer exports the removed authoring surface", () => {
    const surface = dagster as unknown as Record<string, unknown>;
    for (const removed of [
      "DagsterWorkflowTranslator",
      "DagsterIdentifier",
      "DagsterIdentifierScope",
      "isDagsterIdentifier",
      "synthesizeDagsterIdentifier",
      "sanitizeDagsterIdentifier",
      "translateDagsterCondition",
      "assertDagsterPath",
      "assertDagsterStep",
      "assertDagsterImports",
      "DagsterLaunchRequest",
      "DagsterRunHandle",
      "DAGSTER_IMPORT_ALLOWLIST",
      "DAGSTER_GENERATED_HEADER",
      "DAGSTER_RESERVED_IDENTIFIERS",
      "DAGSTER_GENERIC_KINDS",
      "DAGSTER_ROUTER_KINDS",
    ]) {
      expect(surface[removed]).toBeUndefined();
    }
  });

  it("keeps the read-only driver exports", () => {
    const surface = dagster as unknown as Record<string, unknown>;
    expect(typeof surface["DagsterGraphExecutionBackend"]).toBe("function");
    expect(typeof surface["DagsterGraphEventBridge"]).toBe("function");
    expect(typeof surface["DagsterResultMapper"]).toBe("function");
    expect(typeof surface["dagsterBackendCapabilities"]).toBe("function");
    expect(typeof surface["dagsterJobDocument"]).toBe("function");
    expect(Array.isArray(surface["DAGSTER_CAPABILITY_TABLE"])).toBe(true);
  });

  it("declares only the read side and the two gated execution rows as supported", () => {
    const supported = DAGSTER_CAPABILITY_TABLE.filter(
      (row) => row.verdict === "supported"
    );
    expect(supported.map((row) => row.feature).sort()).toEqual(
      [
        "execute existing workflow (launch run)",
        "list / inspect existing workflows",
        "replay / re-execute existing run",
      ].sort()
    );

    const executeRow = DAGSTER_CAPABILITY_TABLE.find(
      (row) => row.feature === "execute existing workflow (launch run)"
    );
    expect(executeRow?.verdict).toBe("supported");
    expect(executeRow?.detail).toContain("executionEnabled");
    expect(executeRow?.detail).toContain(
      DAGSTER_ERROR.EXECUTION_NOT_ENABLED
    );

    const replayRow = DAGSTER_CAPABILITY_TABLE.find(
      (row) => row.feature === "replay / re-execute existing run"
    );
    expect(replayRow?.verdict).toBe("supported");
    expect(replayRow?.detail).toContain("executionEnabled");
    expect(replayRow?.detail).toContain(
      DAGSTER_ERROR.EXECUTION_NOT_ENABLED
    );

    // Every authoring/translation row stays not_supported.
    const authoringRows = DAGSTER_CAPABILITY_TABLE.filter(
      (row) =>
        row.feature !== "list / inspect existing workflows" &&
        row.feature !== "execute existing workflow (launch run)" &&
        row.feature !== "replay / re-execute existing run"
    );
    expect(authoringRows.length).toBeGreaterThan(0);
    for (const row of authoringRows) {
      expect(row.verdict).toBe("not_supported");
    }
  });

  it("exposes a read-only authoring error code", () => {
    expect(DAGSTER_ERROR.AUTHORING_NOT_SUPPORTED).toBe(
      "GRAPH_DAGSTER_AUTHORING_NOT_SUPPORTED"
    );
  });
});
